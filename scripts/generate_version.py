#!/usr/bin/env python3
"""Keep the update identity and OS package version in one reviewed manifest."""
from pathlib import Path
import re
import sys

root = Path(__file__).resolve().parent.parent
manifest = (root / 'pubspec.yaml').read_text()
version = re.search(r'^version: ([0-9]+\.[0-9]+\.[0-9]+\+[0-9]+)$', manifest, re.M)
tag = re.search(r'^lrdp_release_tag: (v[0-9]+\.[0-9]+\.[0-9]+(?:-[0-9A-Za-z.-]+)?)$', manifest, re.M)
if not version or not tag or tag[1][1:].split('-')[0] != version[1].split('+')[0]:
    raise SystemExit('Set matching version and lrdp_release_tag in pubspec.yaml')
content = ('// Generated by scripts/generate_version.py from pubspec.yaml.\n'
           f"const appReleaseTag = '{tag[1]}';\n"
           f"const appPackageVersion = '{version[1]}';\n")
output = root / 'lib/app_version.dart'
if '--check' in sys.argv:
    if not output.exists() or output.read_text() != content:
        raise SystemExit('Run python3 scripts/generate_version.py before building')
else:
    output.write_text(content)
