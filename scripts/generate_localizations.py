#!/usr/bin/env python3
"""Validate translator catalogs and generate synchronous, offline Flutter data."""
from pathlib import Path
import json
import re
import shutil
import subprocess

root = Path(__file__).resolve().parent.parent
catalogs = {language: json.loads((root / f'assets/l10n/{language}.json').read_text())
            for language in ('zh-CN', 'zh-TW', 'en')}
base = catalogs['zh-CN']
for language, messages in catalogs.items():
    if messages.keys() != base.keys():
        raise SystemExit(f'{language}: message IDs differ')
    for key, text in messages.items():
        if not text or sorted(re.findall(r'\{\d+\}', key)) != sorted(re.findall(r'\{\d+\}', text)):
            raise SystemExit(f'{language}: missing text or invalid placeholders: {key}')
literal = json.dumps(catalogs, ensure_ascii=False, indent=2).replace('$', r'\$')
output = root / 'lib/l10n/messages.dart'
output.write_text('// Generated by scripts/generate_localizations.py. Edit assets/l10n/*.json.\n'
                  'const localizedMessages = <String, Map<String, String>>' + literal + ';\n')
dart = shutil.which('dart')
if not dart:
    raise SystemExit('Add the Flutter/Dart SDK to PATH, then rerun')
subprocess.run([dart, 'format', str(output)], check=True)
