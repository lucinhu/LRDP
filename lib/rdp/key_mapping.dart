/// Characters produced by a phone's Latin IME, sent as US Set 1 key presses.
/// Non-ASCII text belongs to the local text composer or the remote IME.
List<int>? rdpCharacterChord(int character) {
  const letters = [
    0x1e,
    0x30,
    0x2e,
    0x20,
    0x12,
    0x21,
    0x22,
    0x23,
    0x17,
    0x24,
    0x25,
    0x26,
    0x32,
    0x31,
    0x18,
    0x19,
    0x10,
    0x13,
    0x1f,
    0x14,
    0x16,
    0x2f,
    0x11,
    0x2d,
    0x15,
    0x2c,
  ];
  if (character >= 0x61 && character <= 0x7a) {
    return [letters[character - 0x61]];
  }
  if (character >= 0x41 && character <= 0x5a) {
    return [0x2a, letters[character - 0x41]];
  }
  const plain = '1234567890-=[]\\;\'`,./';
  const shifted = '!@#\$%^&*()_+{}|:"~<>?';
  const codes = [
    0x02,
    0x03,
    0x04,
    0x05,
    0x06,
    0x07,
    0x08,
    0x09,
    0x0a,
    0x0b,
    0x0c,
    0x0d,
    0x1a,
    0x1b,
    0x2b,
    0x27,
    0x28,
    0x29,
    0x33,
    0x34,
    0x35,
  ];
  final text = String.fromCharCode(character);
  final index = plain.indexOf(text);
  if (index >= 0) return [codes[index]];
  final shift = shifted.indexOf(text);
  if (shift >= 0) return [0x2a, codes[shift]];
  return switch (character) {
    0x08 => [0x0e],
    0x09 => [0x0f],
    0x0a || 0x0d => [0x1c],
    0x20 => [0x39],
    _ => null,
  };
}

